#!/usr/bin/env node
// Writes an "Inputs" table for every tool into docs/tools.md, generated from
// the strict zod schemas in src/tools.mjs, so the reference cannot fall
// behind the code. The prose above each table is written by hand.
//
//   npm run docs          update docs/tools.md
//   npm run docs -- --check   exit 1 if docs/tools.md is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { registerTools } from "../src/tools.mjs";

export const DOC_PATH = new URL("../docs/tools.md", import.meta.url);
const START = "<!-- inputs:start (generated by npm run docs) -->";
const END = "<!-- inputs:end -->";

export function registeredTools() {
  const tools = [];
  registerTools({ registerTool: (name, config) => tools.push({ name, config }) }, () => ({}));
  return tools;
}

// Peels optional/default wrappers. Returns the inner schema, whether the field
// may be left out, its default, and the first description found on the way.
function unwrap(schema) {
  let current = schema, optional = false, defaultValue, description = schema.description;
  for (;;) {
    const def = current._zod.def;
    if (def.type === "optional") optional = true;
    else if (def.type === "default") { optional = true; defaultValue = typeof def.defaultValue === "function" ? def.defaultValue() : def.defaultValue; }
    else break;
    current = def.innerType;
    description = description || current.description;
  }
  return { inner: current, optional, defaultValue, description };
}

const code = value => "`" + String(value) + "`";
const number = value => String(value).replace("-", "−");

function checks(schema) {
  return (schema._zod.def.checks || []).map(check => check._zod.def);
}

function numberValues(schema) {
  let low, high, lowOpen = false, highOpen = false;
  for (const check of checks(schema)) {
    if (check.check === "greater_than") { low = check.value; lowOpen = !check.inclusive; }
    if (check.check === "less_than") { high = check.value; highOpen = !check.inclusive; }
  }
  const integer = schema.isInt;
  const parts = [];
  if (low !== undefined && high !== undefined && !lowOpen && !highOpen) parts.push(`${number(low)} to ${number(high)}`);
  else {
    if (low !== undefined) parts.push(lowOpen ? `> ${number(low)}` : `≥ ${number(low)}`);
    if (high !== undefined) parts.push(highOpen ? `< ${number(high)}` : `≤ ${number(high)}`);
  }
  return { type: integer ? "integer" : "number", values: parts.join(", ") };
}

function stringValues(schema) {
  if (schema.format === "uuid") return "UUID";
  const parts = [];
  for (const check of checks(schema)) {
    if (check.check === "string_format" && check.format === "regex") {
      parts.push(String(check.pattern) === "/^#[0-9a-fA-F]{6}$/" ? code("#RRGGBB") : code(check.pattern));
    }
  }
  if (schema.minLength) parts.push(schema.minLength === 1 ? "not empty" : `at least ${schema.minLength} characters`);
  if (schema.maxLength != null && schema.maxLength < Infinity) parts.push(`at most ${schema.maxLength} characters`);
  return parts.join(", ");
}

function arrayValues(schema) {
  let min, max;
  for (const check of checks(schema)) {
    if (check.check === "min_length") min = check.minimum;
    if (check.check === "max_length") max = check.maximum;
  }
  if (min !== undefined && max !== undefined) return `${min} to ${max} items`;
  if (max !== undefined) return `up to ${max} items`;
  if (min !== undefined) return `at least ${min} items`;
  return "";
}

function describe(schema) {
  const def = schema._zod.def;
  switch (def.type) {
    case "string": return { type: "string", values: stringValues(schema) };
    case "number": return numberValues(schema);
    case "boolean": return { type: "boolean", values: "" };
    case "enum": return { type: "enum", values: Object.values(def.entries).map(code).join(", ") };
    case "literal": return { type: "literal", values: def.values.map(code).join(", ") };
    case "array": {
      const element = unwrap(def.element).inner;
      const kind = element._zod.def.type === "object" ? "objects" : describe(element).type + "s";
      return { type: `array of ${kind}`, values: arrayValues(schema), element };
    }
    case "object": return { type: "object", values: "" };
    default: throw new Error(`tool-docs: no rendering for zod type "${def.type}"`);
  }
}

function rows(shape, prefix) {
  const out = [];
  for (const [key, field] of Object.entries(shape)) {
    const { inner, optional, defaultValue, description } = unwrap(field);
    const info = describe(inner);
    const name = prefix + key;
    let presence = optional ? "optional" : "required";
    if (defaultValue !== undefined) presence = `default ${code(JSON.stringify(defaultValue))}`;
    const elementInfo = info.element ? describe(info.element) : null;
    const values = info.values || (elementInfo && elementInfo.type !== "object" ? elementInfo.values : "");
    out.push(`| ${code(name)} | ${info.type} | ${values} | ${presence} | ${(description || "").replace(/\|/g, "\\|")} |`);
    if (inner._zod.def.type === "object") out.push(...rows(inner._zod.def.shape, `${name}.`));
    if (info.element && info.element._zod.def.type === "object") out.push(...rows(info.element._zod.def.shape, `${name}[].`));
  }
  return out;
}

export function inputsTable(tool) {
  const shape = tool.config.inputSchema._zod.def.shape;
  const body = Object.keys(shape).length
    ? ["| Field | Type | Values | Required | Description |", "|---|---|---|---|---|", ...rows(shape, "")].join("\n")
    : "No inputs.";
  return `${START}\n**Inputs**\n\n${body}\n${END}`;
}

// Puts each tool's table at the end of its "### bitwig_…" section, replacing
// a table from an earlier run.
export function render(doc, tools) {
  let out = doc.split(START).map((part, i) => (i === 0 ? part : part.slice(part.indexOf(END) + END.length))).join("");
  out = out.replace(/\n{3,}/g, "\n\n");
  for (const tool of tools) {
    const heading = `### ${tool.name}\n`;
    const start = out.indexOf(heading);
    if (start < 0) throw new Error(`tool-docs: docs/tools.md has no section for ${tool.name}`);
    const rest = out.slice(start + heading.length);
    const next = rest.search(/\n#{2,3} /);
    const end = next < 0 ? out.length : start + heading.length + next;
    const section = out.slice(start, end).replace(/\s+$/, "");
    out = out.slice(0, start) + section + "\n\n" + inputsTable(tool) + "\n" + out.slice(end);
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const doc = readFileSync(DOC_PATH, "utf8");
  const next = render(doc, registeredTools());
  if (process.argv.includes("--check")) {
    if (next !== doc) {
      console.error("docs/tools.md is out of date. Run: npm run docs");
      process.exit(1);
    }
    console.log("docs/tools.md is up to date.");
  } else {
    writeFileSync(DOC_PATH, next);
    console.log(next === doc ? "docs/tools.md was already up to date." : "Updated docs/tools.md.");
  }
}
